# -*- coding: utf-8 -*-
"""
Turns the NE0NNi* icons (drawn in Illustrator, ../SNS/icons/NE0NNi_icons.ai → ../SNS/icons/svg/) into path data
the site draws inline, so the colors come from tokens.css and not from the files.
Run from web/:  python3 scripts/make-icons.py   →  src/lib/icons.ts

Each icon has two shapes: `fill` (the inside, white in the files) and `ink` (the lines, #0e0e12 in the files).
*_invert files are the versions drawn for black grounds (the shapes differ, not only the colors).
`box` is the drawing's own bounds (the files leave different margins round each drawing), so the site can line
an icon up with the text by its drawn edge.
"""
import math, os, re

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.dirname(WEB), 'SNS', 'icons', 'svg')
OUT = os.path.join(WEB, 'src', 'lib', 'icons.ts')

NAMES = {
    'headphones': 'headphones_b',          # side view with the cable
    'headphones-front': 'headphones_front',
    'stylus': 'stylus_a',
    'stylus-hand': 'stylus_hand',
}

def paths(fname):
    s = open(os.path.join(SRC, fname)).read()
    out = {}
    for m in re.finditer(r'<path id="[^"]*_x5F_(fill|ink)" d="([^"]+)"', s):
        out[m.group(1)] = re.sub(r'\s+', ' ', m.group(2)).strip()
    assert set(out) == {'fill', 'ink'}, fname
    return out

NUM = re.compile(r'-?(?:\d+\.?\d*|\.\d+)(?:[eE]-?\d+)?')


def bounds(*ds):
    """Bounds of path data written with M c s q Z (all Illustrator writes here). Curves are sampled."""
    xs, ys = [], []
    for d in ds:
        x = y = 0.0
        sx = sy = 0.0
        last_c2 = None
        for cmd, args in re.findall(r'([MZcsq])([^MZcsq]*)', d):
            n = [float(v) for v in NUM.findall(args)]
            if cmd == 'M':
                for i in range(0, len(n), 2):
                    x, y = n[i], n[i + 1]; xs.append(x); ys.append(y)
                sx, sy = x, y; last_c2 = None
            elif cmd == 'Z':
                x, y = sx, sy; last_c2 = None
            elif cmd in 'cs':
                step = 6 if cmd == 'c' else 4
                for i in range(0, len(n), step):
                    if cmd == 'c':
                        c1 = (x + n[i], y + n[i + 1]); c2 = (x + n[i + 2], y + n[i + 3]); e = (x + n[i + 4], y + n[i + 5])
                    else:
                        c1 = (2 * x - last_c2[0], 2 * y - last_c2[1]) if last_c2 else (x, y)
                        c2 = (x + n[i], y + n[i + 1]); e = (x + n[i + 2], y + n[i + 3])
                    for k in range(1, 17):
                        t = k / 16; u = 1 - t
                        xs.append(u**3 * x + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t**3 * e[0])
                        ys.append(u**3 * y + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t**3 * e[1])
                    last_c2 = c2; x, y = e
            elif cmd == 'q':
                for i in range(0, len(n), 4):
                    c = (x + n[i], y + n[i + 1]); e = (x + n[i + 2], y + n[i + 3])
                    for k in range(1, 17):
                        t = k / 16; u = 1 - t
                        xs.append(u * u * x + 2 * u * t * c[0] + t * t * e[0]); ys.append(u * u * y + 2 * u * t * c[1] + t * t * e[1])
                    x, y = e; last_c2 = None
    l, t, r, b = math.floor(min(xs)), math.floor(min(ys)), math.ceil(max(xs)), math.ceil(max(ys))
    return [l, t, r - l, b - t]


lines = [
    '/** Generated by scripts/make-icons.py from ../SNS/icons/svg (NE0NNi_icons.ai). Do not edit by hand. */',
    "export type IconName = " + ' | '.join(f"'{k}'" for k in NAMES) + ';',
    'export type IconShapes = { fill: string; ink: string; box: [number, number, number, number] };',
    'export const ICONS: Record<IconName, { day: IconShapes; night: IconShapes }> = {',
]
for key, base in NAMES.items():
    d, n = paths(f'NE0NNi_icons_{base}.svg'), paths(f'NE0NNi_icons_{base}_invert.svg')
    lines.append(f"  '{key}': {{")
    for name, v in (('day', d), ('night', n)):
        box = bounds(v['fill'], v['ink'])
        lines.append(f"    {name}: {{ box: {box}, fill: '{v['fill']}', ink: '{v['ink']}' }},")
        print(key, name, box)
    lines.append('  },')
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(OUT, os.path.getsize(OUT) // 1024, 'KB')
